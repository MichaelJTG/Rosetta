_MARCOS = [MarcoNormativo.ISO_27001_2022]


def _make_llm_con_violacion(
    controles: list[str] | None = None,
    impacto: str = "alta",
) -> Any:
    """Mock LLM que responde con una violación."""
    tool_input = {
        "tiene_violacion": True,
        "controles_incumplidos": controles or ["A.8.24"],
        "cita_normativa": "A.8.24 Uso de la criptografía: Las claves deben gestionarse de forma segura.",
        "justificacion": "Se detectó una clave AWS hardcodeada en el código fuente.",
        "impacto_legal": impacto,
        "accion_mitigacion": "Eliminar la clave del código y usar variables de entorno o un secret manager.",
        "evidencia_auditoria": "Credencial expuesta en commit del PR.",
    }
    tool_call = MagicMock()
    tool_call.tool_input = tool_input
    response = MagicMock()
    response.tool_calls = [tool_call]
    llm = AsyncMock()
    llm.completar = AsyncMock(return_value=response)
    return llm


def _make_llm_sin_violacion() -> Any:
    """Mock LLM que responde sin violación."""
    tool_input = {
        "tiene_violacion": False,
        "controles_incumplidos": [],
        "cita_normativa": "",
        "justificacion": "El cambio es un comentario de código, normativamente neutro.",
        "impacto_legal": "informativa",
        "accion_mitigacion": "",
        "evidencia_auditoria": "",
    }
    tool_call = MagicMock()
    tool_call.tool_input = tool_input
    response = MagicMock()
    response.tool_calls = [tool_call]
    llm = AsyncMock()
    llm.completar = AsyncMock(return_value=response)
    return llm


def _make_llm_sin_tool_call() -> Any:
    """Mock LLM que no invoca ninguna tool (caso degenerado)."""
    response = MagicMock()
    response.tool_calls = []
    response.content = "No sé qué hacer."
    llm = AsyncMock()
    llm.completar = AsyncMock(return_value=response)
    return llm


def _make_rag() -> Any:
    rag = MagicMock()
    rag.recuperar.return_value = []
    return rag


# ---------------------------------------------------------------------------
# Tests: DiffAnalyzer
# ---------------------------------------------------------------------------


class TestDiffAnalyzer:
    @pytest.mark.asyncio
    async def test_secret_genera_violacion(self) -> None:
        analyzer = DiffAnalyzer(llm=_make_llm_con_violacion(), rag=_make_rag())
        result = await analyzer.analizar(DIFF_SECRET_AWS, marcos=_MARCOS)

        assert len(result.violaciones) == 1
        assert "A.8.24" in result.violaciones[0].controles_incumplidos

    @pytest.mark.asyncio
    async def test_secret_bloquea_con_umbral_alta(self) -> None:
        analyzer = DiffAnalyzer(llm=_make_llm_con_violacion(impacto="alta"), rag=_make_rag())
        result = await analyzer.analizar(
            DIFF_SECRET_AWS, marcos=_MARCOS, bloquear_si=Severidad.ALTA
        )
        assert result.bloquear is True

    @pytest.mark.asyncio
    async def test_impacto_bajo_no_bloquea_con_umbral_alta(self) -> None:
        analyzer = DiffAnalyzer(llm=_make_llm_con_violacion(impacto="baja"), rag=_make_rag())
        result = await analyzer.analizar(
            DIFF_NEUTRAL_COMMENT, marcos=_MARCOS, bloquear_si=Severidad.ALTA
        )
        assert result.bloquear is False

    @pytest.mark.asyncio
    async def test_impacto_critico_bloquea_con_cualquier_umbral(self) -> None:
        analyzer = DiffAnalyzer(llm=_make_llm_con_violacion(impacto="critica"), rag=_make_rag())
        result = await analyzer.analizar(
            DIFF_SECRET_AWS, marcos=_MARCOS, bloquear_si=Severidad.BAJA
        )
        assert result.bloquear is True

    @pytest.mark.asyncio
    async def test_comentario_neutro_no_viola(self) -> None:
        analyzer = DiffAnalyzer(llm=_make_llm_sin_violacion(), rag=_make_rag())
        result = await analyzer.analizar(DIFF_NEUTRAL_COMMENT, marcos=_MARCOS)

        assert len(result.violaciones) == 0
        assert result.bloquear is False

    @pytest.mark.asyncio
    async def test_diff_vacio_no_llama_llm(self) -> None:
        llm = _make_llm_con_violacion()
        analyzer = DiffAnalyzer(llm=llm, rag=_make_rag())
        result = await analyzer.analizar(DIFF_VACIO, marcos=_MARCOS)

        llm.completar.assert_not_called()
        assert result.total_hunks_analizados == 0
        assert len(result.violaciones) == 0

    @pytest.mark.asyncio
    async def test_exclude_paths_evita_llamada_llm(self) -> None:
        llm = _make_llm_con_violacion()
        analyzer = DiffAnalyzer(llm=llm, rag=_make_rag())
        result = await analyzer.analizar(
            DIFF_SECRET_AWS, marcos=_MARCOS, exclude_paths=["config.py"]
        )

        llm.completar.assert_not_called()
        assert len(result.violaciones) == 0

    @pytest.mark.asyncio
    async def test_sin_tool_call_no_genera_violacion(self) -> None:
        """Si el LLM no invoca la tool, se trata como sin violación (resiliente)."""
        analyzer = DiffAnalyzer(llm=_make_llm_sin_tool_call(), rag=_make_rag())
        result = await analyzer.analizar(DIFF_SECRET_AWS, marcos=_MARCOS)

        assert len(result.violaciones) == 0
        assert result.bloquear is False

    @pytest.mark.asyncio
    async def test_marcos_usados_en_resultado(self) -> None:
        analyzer = DiffAnalyzer(llm=_make_llm_sin_violacion(), rag=_make_rag())
        marcos = [MarcoNormativo.ISO_27001_2022, MarcoNormativo.ENS_2022]
        result = await analyzer.analizar(DIFF_NEUTRAL_COMMENT, marcos=marcos)

        assert MarcoNormativo.ISO_27001_2022 in result.marcos_usados
        assert MarcoNormativo.ENS_2022 in result.marcos_usados

    @pytest.mark.asyncio
    async def test_total_hunks_analizados_correcto(self) -> None:
        analyzer = DiffAnalyzer(llm=_make_llm_sin_violacion(), rag=_make_rag())
        result = await analyzer.analizar(DIFF_MULTI_ARCHIVO, marcos=_MARCOS)

        assert result.total_hunks_analizados == 2

    @pytest.mark.asyncio
    async def test_violacion_tiene_datos_correctos(self) -> None:
        analyzer = DiffAnalyzer(
            llm=_make_llm_con_violacion(controles=["A.8.24", "A.5.15"]), rag=_make_rag()
        )
        result = await analyzer.analizar(DIFF_SECRET_AWS, marcos=_MARCOS)

        assert len(result.violaciones) == 1
        v = result.violaciones[0]
        assert v.archivo == "config.py"
        assert "A.8.24" in v.controles_incumplidos
        assert "A.5.15" in v.controles_incumplidos
        assert v.impacto_legal == Severidad.ALTA
        assert len(v.lineas_afectadas) > 0

    @pytest.mark.asyncio
    async def test_impacto_invalido_cae_a_media(self) -> None:
        """Severidad desconocida del LLM debe caer a MEDIA sin romper."""
        analyzer = DiffAnalyzer(
            llm=_make_llm_con_violacion(impacto="super_critico"), rag=_make_rag()
        )
        result = await analyzer.analizar(DIFF_SECRET_AWS, marcos=_MARCOS)

        assert result.violaciones[0].impacto_legal == Severidad.MEDIA

    @pytest.mark.asyncio
    async def test_lock_file_no_genera_violacion(self) -> None:
        llm = _make_llm_con_violacion()
        analyzer = DiffAnalyzer(llm=llm, rag=_make_rag())
        result = await analyzer.analizar(DIFF_LOCK_FILE, marcos=_MARCOS)

        llm.completar.assert_not_called()
        assert len(result.violaciones) == 0
