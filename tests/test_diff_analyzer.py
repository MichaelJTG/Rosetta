# Tests: DiffParser
# ---------------------------------------------------------------------------


class TestDiffParser:
    def test_parse_detecta_secret_aws(self) -> None:
        hunks = DiffParser.parse(DIFF_SECRET_AWS)
        assert len(hunks) == 1
        assert hunks[0].archivo == "config.py"
        assert hunks[0].linea_inicio == 1
        assert any("AKIAIOSFODNN7EXAMPLE" in line for line in hunks[0].lineas_anadidas)

    def test_parse_hunk_frozen(self) -> None:
        """DiffHunk debe ser inmutable (frozen=True)."""
        hunks = DiffParser.parse(DIFF_SECRET_AWS)
        with pytest.raises((AttributeError, TypeError)):
            hunks[0].archivo = "otro.py"  # type: ignore[misc]

    def test_parse_comentario_neutro(self) -> None:
        hunks = DiffParser.parse(DIFF_NEUTRAL_COMMENT)
        assert len(hunks) == 1
        assert hunks[0].archivo == "utils.py"
        assert any("ISO 8601" in line for line in hunks[0].lineas_anadidas)

    def test_parse_excluye_package_lock(self) -> None:
        hunks = DiffParser.parse(DIFF_LOCK_FILE)
        assert len(hunks) == 0

    def test_parse_excluye_poetry_lock(self) -> None:
        hunks = DiffParser.parse(DIFF_POETRY_LOCK)
        assert len(hunks) == 0

    def test_parse_excluye_binarios(self) -> None:
        hunks = DiffParser.parse(DIFF_BINARY)
        assert len(hunks) == 0

    def test_parse_diff_vacio(self) -> None:
        assert DiffParser.parse(DIFF_VACIO) == []

    def test_parse_solo_eliminaciones_no_genera_hunk(self) -> None:
        hunks = DiffParser.parse(DIFF_SOLO_ELIMINACIONES)
        assert len(hunks) == 0

    def test_parse_multi_archivo(self) -> None:
        hunks = DiffParser.parse(DIFF_MULTI_ARCHIVO)
        archivos = [h.archivo for h in hunks]
        assert "api/auth.py" in archivos
        assert "utils/helpers.py" in archivos

    def test_parse_exclude_paths_exacto(self) -> None:
        hunks = DiffParser.parse(DIFF_SECRET_AWS, exclude_paths=["config.py"])
        assert len(hunks) == 0

    def test_parse_exclude_paths_glob(self) -> None:
        hunks = DiffParser.parse(DIFF_SECRET_AWS, exclude_paths=["*.py"])
        assert len(hunks) == 0

    def test_parse_exclude_paths_directorio(self) -> None:
        hunks = DiffParser.parse(DIFF_MULTI_ARCHIVO, exclude_paths=["api/**"])
        archivos = [h.archivo for h in hunks]
        assert "api/auth.py" not in archivos
        assert "utils/helpers.py" in archivos

    def test_hunk_tiene_contenido(self) -> None:
        hunks = DiffParser.parse(DIFF_SECRET_AWS)
        assert hunks[0].tiene_contenido is True

    def test_hunk_contenido_anadido(self) -> None:
        hunks = DiffParser.parse(DIFF_SECRET_AWS)
        contenido = hunks[0].contenido_anadido
        assert "AKIAIOSFODNN7EXAMPLE" in contenido
        assert "wJalrXUtnFEMI" in contenido


